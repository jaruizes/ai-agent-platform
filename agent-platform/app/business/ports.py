class ExecutionRepositoryPort(Protocol):
    async def create_execution(self, submission: ExecutionSubmission) -> tuple[UUID, bool]: ...
    async def claim_next(self, *, worker_id: str, lease_seconds: int) -> dict[str, Any] | None: ...
    async def heartbeat(self, execution_id: UUID, *, worker_id: str, lease_seconds: int) -> bool: ...
    async def release_lease(self, execution_id: UUID, *, worker_id: str) -> None: ...
    async def get_control(self, execution_id: UUID) -> dict[str, Any]: ...
    async def request_pause(self, execution_id: UUID, *, reason: str | None) -> bool: ...
    async def request_cancel(self, execution_id: UUID, *, reason: str | None) -> bool: ...
    async def resume_execution(self, execution_id: UUID) -> bool: ...
    async def retry_failed_execution(self, execution_id: UUID, *, reason: str | None) -> bool: ...
    async def mark_suspended(self, execution: dict[str, Any], *, status: str, reason: str) -> None: ...
    async def mark_cancelled(self, execution: dict[str, Any], *, reason: str) -> None: ...
    async def complete(self, execution: dict[str, Any], *, normalized_intent: str, result: dict[str, Any]) -> None: ...
    async def fail(self, execution: dict[str, Any], error: dict[str, Any]) -> None: ...
    async def get(self, execution_id: UUID) -> dict[str, Any] | None: ...
    async def save_plan(self, execution: dict[str, Any], *, plan: dict[str, Any], planner_model: str, planner_usage: dict[str, Any], validation: dict[str, Any]) -> None: ...
    async def mark_plan_running(self, execution: dict[str, Any]) -> None: ...
    async def mark_plan_completed(self, execution: dict[str, Any]) -> None: ...
    async def mark_plan_failed(self, execution: dict[str, Any]) -> None: ...
    async def mark_step_started(self, execution: dict[str, Any], *, step_id: str, detail: dict[str, Any]) -> None: ...
    async def get_step_checkpoint(self, execution_id: UUID, step_id: str) -> dict[str, Any] | None: ...
    async def mark_step_attempt(self, execution: dict[str, Any], *, step_id: str) -> int: ...
    async def mark_step_retrying(self, execution: dict[str, Any], *, step_id: str, error: dict[str, Any], delay_seconds: float) -> None: ...
    async def enforce_step_approval_policy(self, execution: dict[str, Any], *, step_id: str, reason: str, approval_source: str, tool_side_effect: str, tool_approval_policy: str) -> None: ...
    async def mark_step_waiting_approval(self, execution: dict[str, Any], *, step_id: str, reason: str) -> None: ...
    async def decide_step_approval(self, execution_id: UUID, step_id: str, *, approved: bool, actor: str, comment: str | None) -> bool: ...
    async def mark_step_completed(self, execution: dict[str, Any], *, step_id: str, output: dict[str, Any], usage: dict[str, Any]) -> None: ...
    async def mark_step_failed(self, execution: dict[str, Any], *, step_id: str, error: dict[str, Any]) -> None: ...
    async def get_orchestration(self, execution_id: UUID) -> dict[str, Any] | None: ...
    async def pending_outbox(self, limit: int = 50) -> list[dict[str, Any]]: ...
    async def mark_published(self, event_id: UUID) -> None: ...
    async def mark_publish_attempt(self, event_id: UUID) -> None: ...


